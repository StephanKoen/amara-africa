/**
 * The English journey with its text replaced by the Arabic edition. Images,
 * slugs and gallery structure come from lib/journeys.ts; section galleries are
 * re-keyed to the Arabic headings so they land in the same places.
 */
export function arabicJourney(slug: string): Journey | undefined {
  const en = journeys.find((j) => j.slug === slug);
  const ar = journeysAr[slug];
  if (!en || !ar) return undefined;
  return {
    ...en,
    tag: ar.tag,
    title: ar.title,
    titleItalic: ar.titleItalic,
    oneliner: ar.oneliner,
    duration: ar.duration,
    territory: ar.territory,
    highlights: ar.highlights,
    inclusions: ar.inclusions,
    exclusions: ar.exclusions,
    idealFor: ar.idealFor,
    body: ar.body,
    bestSeason: ar.bestSeason,
    excursions: ar.excursions,
    seoTitle: ar.seoTitle,
    seoDescription: ar.seoDescription,
    sectionGalleries:
      ar.galleryHeadings && en.sectionGalleries
        ? en.sectionGalleries.map((g, i) => ({
            ...g,
            afterHeading: ar.galleryHeadings![i] ?? g.afterHeading,
          }))
        : undefined,
  };
}

export const arabicJourneys: Journey[] = journeys
  .map((j) => arabicJourney(j.slug))
  .filter((j): j is Journey => Boolean(j));
